import {createAvatar} from '@dicebear/core';
import * as openPeeps from '@dicebear/open-peeps';
import sharp from 'sharp';
import {readFileSync,writeFileSync,mkdirSync,copyFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
import {tmpdir} from 'node:os';
process.env.XDG_CACHE_HOME ||= resolve(tmpdir(),'slangverse-avatar-cache');
mkdirSync(process.env.XDG_CACHE_HOME,{recursive:true});

const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const assetRoot=resolve(root,'assets/profile-pictures');
const check=process.argv.includes('--check');
const rows=[
 ['mira','@miramoments','longCurly'],['campus','@campusfeed','hatHip'],
 ['ari','@ariatwork','short2'],['matchday','@matchdaychat','hatBeanie'],
 ['ben','@benchside','short4'],['lila','@lilalistens','bun'],
 ['dea','@deasays','mediumBangs'],['jo','@justjo','twists'],
 ['townloop','@townloop','grayShort'],['naya','@naya','hijab'],
 ['sam','@sam','flatTop'],['kai','@confuseduser','medium2'],
 ['guest_01',null,'bangs'],['guest_02',null,'afro'],['guest_03',null,'short1'],
 ['guest_04',null,'long'],['guest_05',null,'cornrows'],['guest_06',null,'turban'],
 ['guest_07',null,'bantuKnots'],['guest_08',null,'grayMedium'],
 ['player','@you','pomp'],['default',null,'mediumStraight']
];
const backgrounds=['f6dfd3','e7ebd7','f3e4c5','dce6e9'];
const skins=['ffdbb4','edb98a','d08b5b','ae5d29','694d3d'];
const source={style:'Open Peeps',creator:'Pablo Stanley',url:'https://www.openpeeps.com/',
 license:'CC0-1.0',licenseUrl:'https://creativecommons.org/publicdomain/zero/1.0/',renderer:'DiceBear 9.4.2'};
const previous=check?JSON.parse(readFileSync(resolve(assetRoot,'catalog.json'),'utf8')):null;
const avatars=[];
for(const [i,[id,handle,head]] of rows.entries()){
 const seed=`slangverse-pfp-v1-${id}`;
 const options={seed,size:256,backgroundColor:[backgrounds[i%backgrounds.length]],
  head:[head],face:['calm','smile','cute'],skinColor:[skins[i%skins.length]],
  clothingColor:['ce7566','839375','c79956'],accessories:['glasses','glasses2'],
  accessoriesProbability:20,facialHairProbability:0,maskProbability:0,scale:110};
 const svg=createAvatar(openPeeps,options).toString();
 const svgPath=`source/pfp_${id}.svg`,pngPath=`android-res/drawable-nodpi/pfp_${id}.png`;
 if(!check){
  mkdirSync(dirname(resolve(assetRoot,svgPath)),{recursive:true});
  mkdirSync(dirname(resolve(assetRoot,pngPath)),{recursive:true});
  writeFileSync(resolve(assetRoot,svgPath),svg);
  await sharp(Buffer.from(svg)).png().toFile(resolve(assetRoot,pngPath));
 }else if(readFileSync(resolve(assetRoot,svgPath),'utf8')!==svg)throw Error(`Stale SVG: ${id}`);
 const png=readFileSync(resolve(assetRoot,pngPath));
 const info=await sharp(png).metadata();
 if(info.width!==256||info.height!==256)throw Error(`Invalid PNG size: ${id}`);
 const entry={id,handle,seed,options,svg:svgPath,png:pngPath,sha256:createHash('sha256').update(png).digest('hex')};
 if(check&&JSON.stringify(previous.avatars[i])!==JSON.stringify(entry))throw Error(`Stale catalog or picture: ${id}`);
 avatars.push(entry);
}
const catalog={schemaVersion:1,source,defaultId:'default',fallbackIds:rows.filter(r=>r[0].startsWith('guest_')).map(r=>r[0]),avatars};
const kotlin=`// Generated by tools/profile-pictures/generate.mjs. Do not edit this registry.\npackage id.slangverse.app\n\ninternal object ProfilePictureCatalog {\n    val ids: Set<String> = setOf(${avatars.map(a=>`"${a.id}"`).join(', ')})\n    val handles: Map<String, String> = mapOf(\n${avatars.filter(a=>a.handle).map(a=>`        "${a.handle}" to "${a.id}"`).join(',\n')}\n    )\n    val fallbackIds: List<String> = listOf(${catalog.fallbackIds.map(id=>`"${id}"`).join(', ')})\n    fun drawable(id: String): Int = when (id) {\n${avatars.map(a=>`        "${a.id}" -> R.drawable.pfp_${a.id}`).join('\n')}\n        else -> R.drawable.pfp_default\n    }\n}\n`;
const backendCatalogPath=resolve(root,'backend/data/profile-pictures.json');
const backendCatalog={schemaVersion:1,source,defaultId:catalog.defaultId,fallbackIds:catalog.fallbackIds,
 avatars:avatars.map(({id,handle})=>({id,handle}))};
const kotlinPath=resolve(root,'android/app/src/main/java/id/slangverse/app/ProfilePictureCatalog.kt');
if(check){
 if(JSON.stringify(previous)!==JSON.stringify(catalog))throw Error('Stale catalogue metadata');
 if(JSON.stringify(JSON.parse(readFileSync(backendCatalogPath,'utf8')))!==JSON.stringify(backendCatalog))throw Error('Stale backend registry');
 if(readFileSync(kotlinPath,'utf8')!==kotlin)throw Error('Stale Android registry');
 console.log(`Verified ${avatars.length} local avatars, checksums, licence metadata and Android registry.`);
}else{
 writeFileSync(resolve(assetRoot,'catalog.json'),JSON.stringify(catalog,null,2)+'\n');
 writeFileSync(kotlinPath,kotlin);
 writeFileSync(backendCatalogPath,JSON.stringify(backendCatalog,null,2)+'\n');
 copyFileSync(resolve(root,'tools/profile-pictures/node_modules/@dicebear/open-peeps/LICENSE'),resolve(assetRoot,'LICENSE-OPEN-PEEPS.txt'));
 copyFileSync(resolve(root,'tools/profile-pictures/node_modules/@dicebear/core/LICENSE'),resolve(assetRoot,'LICENSE-DICEBEAR-CORE.txt'));
 const tiles=[];
 for(const [i,avatar] of avatars.entries()){
  const left=(i%6)*128,top=Math.floor(i/6)*152;
  tiles.push({input:await sharp(resolve(assetRoot,avatar.png)).resize(112,112).toBuffer(),left:left+8,top});
  tiles.push({input:Buffer.from(`<svg width="128" height="32"><text x="64" y="22" text-anchor="middle" font-family="sans-serif" font-size="13" fill="#332a25">${avatar.id}</text></svg>`),left,top:top+112});
 }
 await sharp({create:{width:768,height:Math.ceil(avatars.length/6)*152,channels:4,background:'#faf6ee'}}).composite(tiles).png().toFile(resolve(assetRoot,'preview.png'));
 console.log(`Generated ${avatars.length} Open Peeps profile pictures.`);
}
